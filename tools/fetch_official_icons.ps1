# Refreshes the bundled official icon sets in ../official/ from upstream:
#   - KOReader         resources/icons/mdlight  -> official/mdlight
#   - Simple UI plugin icons                    -> official/simpleui
#
# Usage (PowerShell 5+):  ./tools/fetch_official_icons.ps1 [-KOReaderRef master] [-SimpleUIRef main]

param(
    [string]$KOReaderRef = "master",
    [string]$SimpleUIRef = "main"
)

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
$official = Join-Path $root "official"

function Sync-IconSet {
    param(
        [string]$Repo,
        [string]$Ref,
        [string]$Prefix,
        [string]$Destination
    )
    $commit = Invoke-RestMethod "https://api.github.com/repos/$Repo/commits/$Ref"
    $sha = $commit.sha
    $tree = Invoke-RestMethod "https://api.github.com/repos/$Repo/git/trees/${sha}?recursive=1"
    if ($tree.truncated) { throw "GitHub tree listing for $Repo is truncated" }
    $files = $tree.tree | Where-Object {
        $_.type -eq "blob" -and $_.path.StartsWith($Prefix) -and $_.path.ToLower().EndsWith(".svg")
    }
    if (-not $files) { throw "No SVG files found under $Prefix in $Repo@$sha" }

    if (Test-Path $Destination) { Remove-Item -Recurse -Force $Destination }
    New-Item -ItemType Directory -Force -Path $Destination | Out-Null
    foreach ($file in $files) {
        $relative = $file.path.Substring($Prefix.Length)
        $target = Join-Path $Destination $relative
        New-Item -ItemType Directory -Force -Path (Split-Path -Parent $target) | Out-Null
        Invoke-WebRequest -UseBasicParsing "https://raw.githubusercontent.com/$Repo/$sha/$($file.path)" -OutFile $target
        if ((Get-Item $target).Length -ne $file.size) { throw "Size mismatch: $($file.path)" }
    }
    Write-Host "$Repo@$sha -> $($files.Count) icons"
    return "$Repo@$sha ($($files.Count) icons, $Prefix)"
}

$lines = @()
$lines += Sync-IconSet -Repo "koreader/koreader" -Ref $KOReaderRef `
    -Prefix "resources/icons/mdlight/" -Destination (Join-Path $official "mdlight")
$lines += Sync-IconSet -Repo "doctorhetfield-cmd/simpleui.koplugin" -Ref $SimpleUIRef `
    -Prefix "icons/" -Destination (Join-Path $official "simpleui")

$header = @(
    "Bundled official icon sets, used as the restore source by Icon Pack Manager.",
    "Generated by tools/fetch_official_icons.ps1 on $((Get-Date).ToUniversalTime().ToString('yyyy-MM-dd'))",
    "",
    "KOReader icons: AGPL-3.0 (https://github.com/koreader/koreader)",
    "Simple UI icons: GPL-3.0 (https://github.com/doctorhetfield-cmd/simpleui.koplugin)",
    ""
)
Set-Content -Encoding UTF8 -Path (Join-Path $official "SOURCE.txt") -Value ($header + $lines)
